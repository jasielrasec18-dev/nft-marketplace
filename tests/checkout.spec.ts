test('price revalidation changes the summary but requires another confirmation before creating', async ({ page }) => {
  await openCheckout(page, 'price-changed')
  await connect(page)
  let posts = 0
  page.on('request', (req) => { if (req.method() === 'POST' && new URL(req.url()).pathname === '/api/orders') posts++ })
  await confirm(page).click()
  await expect(page.getByRole('status').filter({ hasText: 'Revise o resumo e confirme novamente.' })).toBeVisible()
  await expect(form(page).getByTestId('order-total')).toHaveText('1.295 ETH')
  expect(posts).toBe(0)
  await create(page)
  expect(posts).toBe(1)
})
