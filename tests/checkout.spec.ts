test('timeout recovery after reload reuses the exact key and payload and returns one order', async ({ page }) => {
  test.setTimeout(45000)
  await openCheckout(page, 'order-timeout')
  await connect(page)
  const attempts: { key: string | undefined; body: string | null }[] = []
  page.on('request', (req) => { if (req.method() === 'POST' && new URL(req.url()).pathname === '/api/orders') attempts.push({ key: req.headers()['idempotency-key'], body: req.postData() }) })
  await confirm(page).click()
  await expect(page.getByRole('button', { name: 'Recuperar pedido', exact: true })).toBeEnabled({ timeout: 18000 })
  await page.reload()
  await page.getByRole('button', { name: 'Recuperar pedido', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pagamento em processamento' })).toBeVisible()
  expect(attempts).toHaveLength(2)
  expect(attempts[0]?.key).toBeTruthy()
  expect(attempts[1]).toEqual(attempts[0])
  const state = await control<{ counts: { orders: number } }>(page, 'GET', '/__mock/state')
  expect(state.counts.orders).toBe(1)
})
