import { test, expect, type Page } from '@playwright/test'
import type { AxiosInstance } from 'axios'
import type { Order } from '../src/contracts/order'
async function control<T = unknown>(page: Page, method: string, url: string, data?: unknown): Promise<T> {
  return page.evaluate(async (input) => {
    const path = '/src/api/client.ts'
    const module = await import(path) as { createApiClient: (options: { baseURL: string; timeoutMs: number }) => AxiosInstance }
    return (await module.createApiClient({ baseURL: '/api', timeoutMs: 10000 }).request(input)).data as T
  }, { method, url, data })
}
const form = (page: Page) => page.getByRole('form', { name: 'Finalizar compra', exact: true })
const confirm = (page: Page) => form(page).getByRole('button', { name: 'Confirmar compra', exact: true })
async function openCheckout(page: Page, scenario = 'default') {
  await control(page, 'POST', '/auth/login', { email: 'collector@example.com', password: 'Jungle123!' })
  await control(page, 'PATCH', '/__mock/scenario', { scenario, latencyMs: 0 })
  await page.goto('/checkout')
  await expect(form(page).getByTestId('order-total')).toHaveText('1.195 ETH')
}
async function connect(page: Page, decision = 'Autorizar conexão') {
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Conectar carteira', exact: true })
  await dialog.getByRole('button', { name: decision, exact: true }).click()
  await expect(dialog).toHaveCount(0)
}
async function create(page: Page) {
  const response = page.waitForResponse((res) => new URL(res.url()).pathname === '/api/orders' && res.request().method() === 'POST' && res.ok())
  await confirm(page).click()
  return await (await response).json() as Order
}
