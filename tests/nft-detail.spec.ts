test('keyboard operates editions, quantity, tabs, related links and acquisition', async ({ page }) => {
  await page.goto('/nfts/nft-002')
  await expect(title(page, 'Jungle Panther #002')).toBeVisible()
  const standard = page.getByRole('radio', { name: 'Standard', exact: true })
  const limited = page.getByRole('radio', { name: 'Limited', exact: true })
  await standard.focus()
  await page.keyboard.down('ArrowRight')
  await expect(limited).toBeChecked()
  await page.keyboard.up('ArrowRight')
  await page.keyboard.press('Tab')
  await expect(plus(page)).toBeFocused()
  await page.keyboard.press('Space')
  await expect(quantity(page)).toHaveText('2')
  await minus(page).focus()
  await page.keyboard.press('Enter')
  await expect(quantity(page)).toHaveText('1')
  const description = page.getByRole('tab', { name: 'Detalhes do NFT' })
  const information = page.getByRole('tab', { name: 'Informações', exact: true })
  await description.focus()
  await page.keyboard.press('ArrowRight')
  await expect(information).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tabpanel')).toContainText('Disponibilidade total')
  await page.keyboard.press('ArrowLeft')
  await expect(description).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tabpanel')).toContainText('Colecionável fictício')
  await add(page).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(plus(page)).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(add(page)).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(purchase(page).getByRole('status').filter({ hasText: 'adicionada(s) ao carrinho' })).toBeVisible()
  await related(page).getByRole('link').first().focus()
  await page.keyboard.press('Enter')
  await expect(title(page, 'Jungle Panther #030')).toBeVisible()
})
