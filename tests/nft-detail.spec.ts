test('direct detail and refresh render authoritative HTTP data without visiting Home', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  const response = page.waitForResponse((res) => new URL(res.url()).pathname === '/api/nfts/nft-001' && res.ok())
  await page.goto('/nfts/nft-001')
  const nft = await (await response).json() as NFT
  await expect(title(page, nft.name)).toBeVisible()
  await expect(page.getByTestId('nft-unit-price')).toHaveText('1.19 ETH')
  await expect(purchase(page)).toContainText(nft.description)
  await expect(page.getByRole('radio', { name: 'Standard', exact: true })).toBeChecked()
  await expect(page.getByRole('radio', { name: 'Limited · Esgotada', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Favoritar · em breve' })).toBeDisabled()
  await expect(add(page)).toBeEnabled()
  const media = page.getByRole('region', { name: 'Galeria do NFT' }).getByRole('img')
  await expect(media).toHaveAttribute('src', nft.imageUrl)
  await expect(media).toHaveAttribute('alt', nft.name)
  await expect.poll(() => media.evaluate((img) => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  const bounds = await media.boundingBox()
  expect(Math.abs((bounds?.width ?? 0) - (bounds?.height ?? 0))).toBeLessThan(1)
  await expect(related(page).getByRole('article')).toHaveCount(5)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.getByTestId('nft-detail-content').evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe((page.viewportSize()?.width ?? 0) >= 768 ? 2 : 1)
  await page.screenshot({ path: testInfo.outputPath('detail.png'), fullPage: true, animations: 'disabled' })
  await page.getByTestId('nft-detail-content').screenshot({ path: testInfo.outputPath('detail-content.png'), animations: 'disabled' })
  await page.reload()
  await expect(title(page)).toBeVisible()
  await expect(add(page)).toBeEnabled()
  expect(errors).toEqual([])
})

