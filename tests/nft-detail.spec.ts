async function control<T = unknown>(page: Page, method: string, url: string, data?: unknown): Promise<T> {
  return page.evaluate(async (input) => {
    const modulePath = '/src/api/client.ts'
    const module = await import(modulePath) as { createApiClient: (options: { baseURL: string; timeoutMs: number }) => AxiosInstance }
    const api = module.createApiClient({ baseURL: '/api', timeoutMs: 10000 })
    return (await api.request({ method: input.method, url: input.url, data: input.data })).data as T
  }, { method, url, data })
}
