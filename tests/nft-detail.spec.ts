test('guest add-to-cart waits for HTTP confirmation and survives refresh', async ({ page }) => {
  await page.goto('/nfts/nft-002')
  await expect(title(page, 'Jungle Panther #002')).toBeVisible()
  await page.getByRole('radio', { name: 'Limited', exact: true }).click()
  await plus(page).click()
  await control(page, 'PATCH', '/__mock/scenario', { scenario: 'slow-network', latencyMs: 1500 })
  const response = page.waitForResponse((res) => new URL(res.url()).pathname === '/api/cart/items' && res.request().method() === 'POST')
  await add(page).click()
  await expect(page.getByRole('button', { name: 'Adicionando…' })).toBeDisabled()
  await expect(plus(page)).toBeDisabled()
  const result = await response
  expect(result.status()).toBe(201)
  expect(result.request().postDataJSON()).toEqual({ nftId: 'nft-002', editionId: 'limited', quantity: 2 })
  await expect(purchase(page).getByRole('status').filter({ hasText: 'adicionada(s) ao carrinho' })).toBeVisible()
  await control(page, 'PATCH', '/__mock/scenario', { scenario: 'default', latencyMs: 0 })
  await page.reload()
  await expect(title(page, 'Jungle Panther #002')).toBeVisible()
  const cart = await control<Cart>(page, 'GET', '/cart')
  expect(cart.owner.kind).toBe('guest')
  expect(cart.items).toHaveLength(1)
  expect(cart.items[0]).toMatchObject({ nftId: 'nft-002', editionId: 'limited', quantity: 2 })
})

